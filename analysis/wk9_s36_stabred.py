#!/usr/bin/env python3
"""
Session 36 -- the stabiliser reduction at GENERAL weights.

Lemma (docs/stabiliser_reduction.md).  Let lam have blocks of equal parts
B_1..B_t (sizes k_b, values m_b), so Stab_W(lam) = prod S_{k_b} acts on the
lam-weight space of C[W]_delta by permuting variable indices within blocks.
Every highest-weight vector v of weight lam satisfies

        P_w v = chi_lam(w) v,      chi_lam(w) = prod_b sgn(w|_{B_b})^{m_b}.

Proof: P_w v has weight w(lam) = lam and lies in the irreducible V_lam
generated by v, whose lam-weight space is one-dimensional; the scalar is
intrinsic to V_lam (P_w in G), and on the leading-minor model
prod_k Delta_k^{lam_k - lam_{k+1}} a transposition (i i+1) inside a block of
value m negates every Delta_k with k >= i+1, total (-1)^{lam_{i+1}} = (-1)^m.
At rectangular lam this is s33's sign^delta lemma.

Consequence: HWV_lam  <=  V_chi := chi_lam-isotypic part of the weight space,
of dimension n_chi ~ N_S / |Stab|.  This module runs the s30 pipeline on the
isotypic basis (twisted orbit sums; orbits whose twisted sum vanishes drop
out), restricts EVERY simple raising operator to V_chi, deduplicates rows by
the common stabiliser H = Stab(lam) ∩ Stab(lam + e_i - e_{i+1}) (rows in one
H-orbit are proportional by chi; chi-obstructed fixed rows must vanish and are
asserted to), takes the kernel by the certified compressed route of
docs/e4_hunt.md section 4 (exact blocked route available for validation), and
evaluates at points exactly as wk8_s30_core.measure does.

NOTE on the one-operator shortcut of s33: ker(E_12) alone sufficed there
because A_4 is 2-transitive so even conjugators reach every E_ij.  At general
lam the stabiliser is a proper Young subgroup and is not transitive on pairs;
every simple raising operator is applied here.  Only the isotypic restriction
generalises.

Conventions inherited verbatim from wk8_s30_core: corrected raising rule
E_ij c_alpha = (alpha_i + 1) c_{alpha + e_i - e_j}; flint nmod_mat for every
rank/nullspace; house primes P1, P2; det points det_4(sum s_i A_i); pad points
are TRUE padded-permanent restrictions x_0 . per_3(x_1..x_9) with every x_t a
random linear form in s_1..s_r (per_padded(3,4) through restrict()) -- never
l . (random cubic).
"""
