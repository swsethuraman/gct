def log(*a):
    print(*a, file=sys.stderr); sys.stderr.flush()

# ------------------------------------------------------------- the stabiliser
def blocks_of(lam):
    """indices grouped by equal value, in order of first appearance."""
    out, seen = [], {}
    for i, v in enumerate(lam):
        if v not in seen: seen[v] = len(out); out.append([])
        out[seen[v]].append(i)
    return out

def perm_sign(seq):
    s = 1
    for i in range(len(seq)):
        for j in range(i + 1, len(seq)):
            if seq[i] > seq[j]: s = -s
    return s

def stab_group(lam, fix=()):
    """[(perm tuple on range(r), chi_lam(perm))] for the Young subgroup
    Stab_W(lam), optionally restricted to the elements fixing `fix` pointwise
    (the common stabiliser H used for row dedup)."""
    r = len(lam)
    blks = blocks_of(lam)
    out = []
    per_block = []
    for B in blks:
        m = lam[B[0]]
        opts = []
        for img in itertools.permutations(B):
            if any(b in fix and c != b for b, c in zip(B, img)): continue
            sg = perm_sign(img)
            opts.append((tuple(zip(B, img)), sg if m % 2 else 1))
        per_block.append(opts)
    for combo in itertools.product(*per_block):
        p = list(range(r)); ch = 1
        for pairs, c in combo:
            for b, im in pairs: p[b] = im
            ch *= c
        out.append((tuple(p), ch))
    return out

def perm_tables(n, r, group):
    """monomial-index permutation tables: (sigma.alpha)[sigma(i)] = alpha[i]."""
    A = exps(n, r); idx = {a: k for k, a in enumerate(A)}
    tabs = []
    for p, ch in group:
        tab = [0] * len(A)
        for k, al in enumerate(A):
            nx = [0] * r
            for i in range(r): nx[p[i]] = al[i]
            tab[k] = idx[tuple(nx)]
        tabs.append((tab, ch))
    return tabs

# --------------------------------------------------------- isotypic basis
def orbit_setup(n, r, delta, lam, verbose=True):
    """basis (weight-lam monomials) and the chi-valid twisted orbit sums as
    dicts multiset -> +-1.  Returns (basis, vecs, group)."""
    lam = tuple(lam) + (0,) * (r - len(lam))
    basis = monomials(n, r, delta, lam)
    group = stab_group(lam)
    tabs = perm_tables(n, r, group)
    seen, vecs, dropped = set(), [], 0
    for m in basis:
        if m in seen: continue
        acc = {}
        for tab, ch in tabs:
            im = tuple(sorted(tab[i] for i in m))
            acc[im] = acc.get(im, 0) + ch
        for im in acc: seen.add(im)
        if acc[m] == 0: dropped += 1; continue      # chi nontrivial on stabiliser
        st = len(group) // len(acc)
        assert all(abs(v) == st for v in acc.values()), (m, acc)
        vecs.append({im: (1 if v > 0 else -1) for im, v in acc.items()})
    if verbose:
        log(f"  lam={lam}: N_S={len(basis)} |Stab|={len(group)} n_chi={len(vecs)} "
            f"(orbits dropped: {dropped})")
    return basis, vecs, group

def n_chi_of(n, r, delta, lam):
    b, v, g = orbit_setup(n, r, delta, lam, verbose=False)
    return len(b), len(v), len(g)

# ------------------------------------------------ reduced raising operators
def reduced_rows(n, r, delta, lam, vecs, verbose=True):
    """Rows of every simple raising operator E_{i,i+1} restricted to V_chi,
    one canonical representative per H-orbit of target monomials
    (H = Stab(lam) ∩ Stab(lam')), as {col: val} dicts.  chi-obstructed
    H-fixed target rows must cancel exactly (asserted)."""
    lam = tuple(lam) + (0,) * (r - len(lam))
    A = exps(n, r); idx = {a: k for k, a in enumerate(A)}
    rows_all = []
    nfixed_checked = 0
    for i in range(r - 1):
        j = i + 1
        if lam[j] == 0: continue
        H = stab_group(lam, fix=(i, j))
        Htabs = perm_tables(n, r, H)
        canon_cache = {}
        def canon(t):
            """(canonical rep, is_obstructed)"""
            c = canon_cache.get(t)
            if c is not None: return c
            best, obstructed = t, False
            for tab, ch in Htabs:
                im = tuple(sorted(tab[k] for k in t))
                if im < best: best = im
                if im == t and ch == -1: obstructed = True
            canon_cache[t] = (best, obstructed)
            return canon_cache[t]
        rows, fx = {}, {}
        for col, vec in enumerate(vecs):
            for m, s in vec.items():
                k = 0
                while k < len(m):
                    a0 = m[k]; c = 1
                    while k + c < len(m) and m[k + c] == a0: c += 1
                    al = A[a0]
                    if al[j] > 0:
                        nb = list(al); nb[j] -= 1; nb[i] += 1
                        nm = tuple(sorted(m[:k] + m[k + 1:k + c] + (idx[tuple(nb)],) + m[k + c:]))
                        val = s * c * (al[i] + 1)
                        cn, obst = canon(nm)
                        if obst:
                            d = fx.setdefault(nm, {}); d[col] = d.get(col, 0) + val
                        elif cn == nm:
                            d = rows.setdefault(nm, {}); d[col] = d.get(col, 0) + val
                    k += c
        bad = [(t, col, v) for t, d in fx.items() for col, v in d.items() if v != 0]
        assert not bad, ("chi-obstructed fixed rows failed to cancel", i, bad[:3])
        nfixed_checked += len(fx)
        kept = [{c: v for c, v in d.items() if v} for d in rows.values()]
        kept = [d for d in kept if d]
        if verbose:
            log(f"    E_{i}{j}: |H|={len(H)} canonical rows {len(kept)} "
                f"(obstructed fixed targets cancelled: {len(fx)})")
        rows_all += kept
    return rows_all, nfixed_checked

# ---------------------------------------------------------------- kernels
def kernel_exact(rows, nchi, prime):
    """one flint rref/nullspace on the full reduced matrix (small cells)."""
    M = _mat(rows, nchi, prime)
    X, nul = M.nullspace()
    rk = nchi - nul
    return nul, rk, [[int(X[i, j]) for i in range(nchi)] for j in range(nul)]

def kernel_compressed(rows, nchi, prime, margin=64, pseed=101, chunk=256):
    """Certified random row compression (docs/e4_hunt.md section 4):
    Agg = P.M with P random over F_prime (rs = n_chi + margin rows), assembled
    in chunks of `chunk` Agg-rows as (M^T @ P_chunk)^T via scipy sparse int64
    (products bounded well inside int64 -- asserted from the actual max |M|
    entry and column fill), reduced mod prime, written straight into ONE
    flint nmod_mat; one flint nullspace.  Peak resident ~ 8 n_chi^2 (flint)
    + 8 nrows chunk (P chunk) + the sparse M.
    Certificate: rank(Agg) <= rank_p(M) <= rank_Q(M) = n_chi - a(plethysm),
    so the caller's assert dim ker(Agg) = a forces equality throughout and
    ker(Agg) = ker_p(M).  Elimination happens only inside flint."""
    import numpy as np
    from scipy import sparse
    t0 = time.time()
    nrows = len(rows)
    rs = nchi + margin
    ri = np.fromiter((r for r, d in enumerate(rows) for _ in d), dtype=np.int64)
    ci = np.fromiter((c for d in rows for c in d), dtype=np.int64)
    vv = np.fromiter((v for d in rows for v in d.values()), dtype=np.int64)
    maxabs = int(np.abs(vv).max())
    MT = sparse.csr_matrix((vv, (ci, ri)), shape=(nchi, nrows), dtype=np.int64)
    colfill = int(np.diff(MT.indptr).max())
    assert maxabs * (prime - 1) * colfill < (1 << 62), ("int64 bound", maxabs, colfill)
    del ri, ci, vv
    rng = np.random.default_rng(pseed * 1000003 + prime % 1000003 + nchi)
    M = nmod_mat(rs, nchi, prime)
    for k0 in range(0, rs, chunk):
        cs = min(chunk, rs - k0)
        Pc = rng.integers(0, prime, (nrows, cs), dtype=np.int64)
        C = (MT @ Pc) % prime                       # (nchi x cs) = Agg[k0:k0+cs].T
        del Pc
        CT = np.ascontiguousarray(C.T); del C
        for k in range(cs):
            rl = CT[k].tolist()
            for j, v in enumerate(rl):
                if v: M[k0 + k, j] = v
        del CT
    del MT
    log(f"    Agg {rs}x{nchi} assembled into flint ({time.time()-t0:.0f}s; "
        f"nrows {nrows}, max|M| {maxabs}, max column fill {colfill})")
    X, nul = M.nullspace()
    rk = nchi - nul
    kern = [[int(X[i, j]) for i in range(nchi)] for j in range(nul)]
    del M, X
    log(f"    nullspace: rank {rk}, dim ker {nul} ({time.time()-t0:.0f}s)")
    return nul, rk, kern

# ---------------------------------------------------------- evaluation
DET4, N_DET = det_form(4)
PAD34, N_PAD = per_padded(3, 4)      # x0 . per_3(x1..x9): the TRUE padded permanent

def point_rows(f, N, n, r, basis, vecs, K, seed, bound, prime):
    """K evaluation rows in chi-coordinates: e[j] = sum_{m in O_j} s_m ev[m]."""
    rnd = random.Random(seed)
    A = exps(n, r)
    out = []
    for _ in range(K):
        As = [[rnd.randint(-bound, bound) for _ in range(N)] for _ in range(r)]
        co = restrict(f, N, n, r, As)
        co = {al: c % prime for al, c in co.items() if c % prime}
        row = []
        for vec in vecs:
            tot = 0
            for m, s in vec.items():
                v = s
                for k in m:
                    c = co.get(A[k], 0)
                    if c == 0: v = 0; break
                    v = v * c % prime
                tot += v
            row.append(tot % prime)
        out.append(row)
    return out

def mult_from(kern, evrows, a, prime):
    """rank of (evaluation rows) . (kernel basis) = number of independent
    evaluation functionals on the HWV space = a - dim(I ∩ HWV)."""
    nchi = len(kern[0])
    ent = []
    for e in evrows:
        for kv in kern:
            ent.append(sum(e[i] * kv[i] for i in range(nchi) if kv[i]) % prime)
    return nmod_mat(len(evrows), a, ent, prime).rank()

# ------------------------------------------------------------ the cell
def measure_reduced(n, r, delta, lam, a_expect, sides=('det', 'pad'),
                    primes=(P1, P2), npts=None, seeds=None, bound=40,
                    route='auto', pseed=101, exact_cap=2500, verbose=True):
    """Full reduced measurement of one cell.  Returns dict with per-prime
    a, rank(R), mult per side, kernel (chi-coords) and sizes."""
    t0 = time.time()
    lam = tuple(lam) + (0,) * (r - len(lam))
    basis, vecs, group = orbit_setup(n, r, delta, lam, verbose)
    nchi = len(vecs)
    rows, nfx = reduced_rows(n, r, delta, lam, vecs, verbose)
    out = dict(lam=lam, N_S=len(basis), stab=len(group), n_chi=nchi,
               nrows=len(rows), per_prime={})
    if route == 'auto':
        route = 'exact' if nchi <= exact_cap else 'compressed'
    out['route'] = route
    if seeds is None: seeds = dict(det=11, pad=29)
    forms = dict(det=(DET4, N_DET), pad=(PAD34, N_PAD))
    K = npts if npts else a_expect + 8
    for prime in primes:
        if route == 'exact':
            a, rk, kern = kernel_exact(rows, nchi, prime)
        else:
            try:
                a, rk, kern = kernel_compressed(rows, nchi, prime, pseed=pseed)
                if a != a_expect:
                    log(f"    compressed certificate missed ({a} != {a_expect}); retry pseed")
                    a, rk, kern = kernel_compressed(rows, nchi, prime, pseed=pseed + 1)
            except MemoryError:
                raise
        assert a == a_expect, ("a mismatch vs plethysm", lam, prime, a, a_expect)
        assert rk == nchi - a, ("rank(R) != n_chi - a", lam, prime, rk, nchi, a)
        res = dict(a=a, rank=rk, kern=kern, mult={})
        if a > 0:
            for sd in sides:
                f, N = forms[sd]
                ev = point_rows(f, N, n, r, basis, vecs, K, seeds[sd], bound, prime)
                res['mult'][sd] = mult_from(kern, ev, a, prime)
        else:
            for sd in sides: res['mult'][sd] = 0
        out['per_prime'][prime] = res
        if verbose:
            log(f"  p={prime}: a={a} rank(R)={rk} mult={res['mult']} npts={K} "
                f"({time.time()-t0:.0f}s)")
    for sd in sides:
        ms = {p: out['per_prime'][p]['mult'][sd] for p in primes}
        assert len(set(ms.values())) == 1, ("primes disagree", lam, sd, ms)
        out['mult_' + sd] = ms[primes[0]]
    out['a'] = a_expect
    out['secs'] = time.time() - t0
    return out

def expand(vecs, kvec, prime):
    """chi-coordinates -> {multiset: value mod prime} on the full basis."""
    outd = {}
    for j, coef in enumerate(kvec):
        if coef == 0: continue
        for m, s in vecs[j].items():
            outd[m] = (outd.get(m, 0) + s * coef) % prime
    return {m: v for m, v in outd.items() if v}
